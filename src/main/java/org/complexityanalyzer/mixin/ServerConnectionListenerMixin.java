package org.complexityanalyzer.mixin;

import io.netty.channel.Channel;
import org.complexityanalyzer.network.multiplex.ProtocolDetector;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(targets = "net.minecraft.server.network.ServerConnectionListener$1")
public class ServerConnectionListenerMixin {
    @Inject(method = "initChannel(Lio/netty/channel/Channel;)V", at = @At("HEAD"))
    private void onInitChannel(Channel ch, CallbackInfo ci) {
        ch.pipeline().addFirst("complexity_multiplexer", new ProtocolDetector());
    }
}